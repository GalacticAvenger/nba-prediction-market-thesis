"""Compute equal-game, pooled-trade, and first-entry final-five longshot gaps.

Input is the cached Phase 5 late-trade panel generated by src/phase5_main.py.
The script filters the regulation final-five window and folded longshot prices
from 5 to 20 cents, inclusive. Estimates and bootstrap intervals are expressed
in percentage points of price minus realized payoff.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import numpy as np
import pandas as pd

DRAWS = 2000
SEED = 6102126

def summarize(z: pd.DataFrame) -> pd.DataFrame:
    z = z.dropna(subset=['game_id', 'A']).copy()
    g = z.groupby('game_id', sort=True)
    n = g.size().to_numpy(float)
    sums = g.A.sum().to_numpy(float)
    means = sums / n
    rng = np.random.default_rng(SEED)
    ids = rng.integers(0, len(n), size=(DRAWS, len(n)))
    eq_draw = means[ids].mean(axis=1)
    trade_draw = sums[ids].sum(axis=1) / n[ids].sum(axis=1)
    first = z.sort_values(['game_id', 'ts'], kind='stable').drop_duplicates('game_id')
    first_values = first.A.to_numpy(float)
    first_ids = rng.integers(0, len(first_values), size=(DRAWS, len(first_values)))
    first_draw = first_values[first_ids].mean(axis=1)
    loo = (means.sum() - means) / (len(means) - 1)
    rows = []
    for label, estimate, draw, observations, games in [
        ('equal_game', means.mean(), eq_draw, len(z), len(means)),
        ('pooled_trade', z.A.mean(), trade_draw, len(z), len(means)),
        ('first_entry', first_values.mean(), first_draw, len(first_values), len(first_values)),
    ]:
        lo, hi = np.quantile(draw, [.025, .975])
        rows.append({
            'window': 'final_five_regulation_minutes',
            'longshot_price_min': .05,
            'longshot_price_max': .20,
            'estimator': label,
            'estimate_pp': estimate * 100,
            'ci95_low_pp': lo * 100,
            'ci95_high_pp': hi * 100,
            'trade_rows': int(observations),
            'games': int(games),
            'bootstrap_draws': DRAWS,
            'seed': SEED,
            'loo_equal_game_min_pp': loo.min() * 100,
            'loo_equal_game_max_pp': loo.max() * 100,
        })
    return pd.DataFrame(rows)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--input', required=True, help='Path to cached phase5_late_trades.parquet')
    ap.add_argument('--output', required=True, help='Path for output CSV')
    args = ap.parse_args()
    d = pd.read_parquet(args.input, columns=['game_id', 'ts', 'late5', 'longshot_price', 'longshot_y'])
    z = d.loc[d.late5 & d.longshot_price.between(.05, .20, inclusive='both')].copy()
    z['A'] = z.longshot_price - z.longshot_y
    result = summarize(z)
    out = Path(args.output); out.parent.mkdir(parents=True, exist_ok=True)
    result.to_csv(out, index=False)
    print(result.to_string(index=False))
    print(f'Input rows: {len(z):,}; eligible games: {z.game_id.nunique():,}')

if __name__ == '__main__':
    main()
